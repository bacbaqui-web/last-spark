import assert from 'node:assert/strict';
import * as THREE from 'three';
import {createRobot} from '../robot.js';
import {createThirdPersonView} from '../third-person.js';
const avatar=createRobot(),view=createThirdPersonView(avatar,['pistol']);
const chest=avatar.bones.find(b=>b.name==='spine_03'),sample={position:new THREE.Vector3(0,1.7,0),yaw:0,pitch:0,weapon:'pistol',speed:10.8,velocity:new THREE.Vector3(0,0,-10.8),grounded:true,dt:1/60};
const heights=[],chestHeights=[];
for(let i=0;i<150;i++){view.pose(sample);if(i>30){heights.push(view.models.pistol.getWorldPosition(new THREE.Vector3()).y);chestHeights.push(chest.getWorldPosition(new THREE.Vector3()).y);}}
assert(Math.max(...heights)-Math.min(...heights)>.003,'forward carry follows a restrained portion of body lift');
assert(Math.max(...chestHeights)-Math.min(...chestHeights)>.025,'forward chest follows body lift');
const carryMean=heights.reduce((a,b)=>a+b,0)/heights.length;
for(let i=0;i<45;i++)view.pose({...sample,firing:true,flash:i%3===0});
const firingHeight=view.models.pistol.getWorldPosition(new THREE.Vector3()).y;
assert(firingHeight>carryMean+.06,'firing raises weapon toward the face and shoulder');
const model=view.models.pistol,trigger=new THREE.Vector3(...model.userData.triggerGrip),hand=avatar.arms[1].hand;
assert(model.localToWorld(trigger).distanceTo(hand.getWorldPosition(new THREE.Vector3()))<.001,'weapon grip stays attached to trigger hand');
console.log('PASS: moving body carries weapon, firing raises shoulder pose, trigger grip stays attached');
const beforeBoost=model.getWorldPosition(new THREE.Vector3());
for(let i=0;i<15;i++)view.pose({...sample,speed:30,velocity:new THREE.Vector3(0,0,-30),boostPhase:i/15,boostDirection:new THREE.Vector3(0,0,-1),firing:false});
assert(model.getWorldPosition(new THREE.Vector3()).y>beforeBoost.y-.22,'third-person boost keeps raised gun instead of dropping it');
assert(model.localToWorld(new THREE.Vector3(...model.userData.triggerGrip)).distanceTo(hand.getWorldPosition(new THREE.Vector3()))<.001,'boost retains trigger-hand grip');
console.log('PASS: third-person boost retains weapon carry and shoulder state');
for(let i=0;i<45;i++)view.pose({...sample,firing:true});
const beforeJump=model.getWorldPosition(new THREE.Vector3()).y;
for(let i=0;i<15;i++)view.pose({...sample,grounded:false,jetJump:.32-i/60,firing:false});
assert(model.getWorldPosition(new THREE.Vector3()).y>beforeJump-.22,'second jump retains raised third-person grip');
assert(model.localToWorld(new THREE.Vector3(...model.userData.triggerGrip)).distanceTo(hand.getWorldPosition(new THREE.Vector3()))<.001,'second jump keeps gun attached to hand');
console.log('PASS: jet-assisted second jump retains weapon grip');
