import assert from 'node:assert/strict';
import * as T from 'three';
import {RoundedBoxGeometry} from 'three/addons/geometries/RoundedBoxGeometry.js';
import {flightCargoSnapshot,createFlightScene} from '../deployment-flight-scene.js';

const root=new T.Group(),geometry=new RoundedBoxGeometry(.5,1,.3,2,.1),material=new T.MeshStandardMaterial({color:0x91ad64});
root.position.set(12,3,-30);root.rotation.y=1.2;
const visible=new T.Mesh(geometry,material);visible.position.y=1;root.add(visible);
const hidden=new T.Group();hidden.visible=false;hidden.add(new T.Mesh(geometry,material));root.add(hidden);
let disposedOriginal=0;geometry.addEventListener('dispose',()=>disposedOriginal++);material.addEventListener('dispose',()=>disposedOriginal++);
const snapshot=flightCargoSnapshot(root),parsed=new T.ObjectLoader().parse(snapshot);
assert.equal(parsed.children.length,1,'hidden combat meshes are excluded');
assert.equal(parsed.children[0].geometry.attributes.position.count,geometry.attributes.position.count,'rounded/custom geometry survives worker serialization');
parsed.updateMatrixWorld(true);assert(parsed.children[0].getWorldPosition(new T.Vector3()).distanceTo(new T.Vector3(0,1,0))<1e-8,'cargo is relative to its root, independent of old sortie position');
assert.equal(snapshot.textures,undefined,'shared game textures are not duplicated into the worker');
assert.equal(disposedOriginal,0,'snapshot leaves gameplay resources alive');
const instances=new T.InstancedMesh(geometry,material,2),matrix=new T.Matrix4();
instances.setMatrixAt(0,matrix.makeTranslation(2,0,0));instances.setMatrixAt(1,matrix.makeTranslation(-2,0,0));root.add(instances);
const instancedCargo=new T.ObjectLoader().parse(flightCargoSnapshot(root));instancedCargo.updateMatrixWorld(true);
assert.equal(instancedCargo.children.length,3);
for(const [i,x]of [[1,2],[2,-2]])assert(instancedCargo.children[i].getWorldPosition(new T.Vector3()).distanceTo(new T.Vector3(x,0,0))<1e-8,'equipment instances keep individual transforms');
const flight=createFlightScene(snapshot);flight.resize(1280,720);flight.update(0);
const meshCount=()=>{let count=0;flight.scene.traverse(o=>{if(o.isMesh)count++;});return count;};
const count=meshCount(),initial=flight.drone.children.filter(o=>o.isGroup).map(o=>o.rotation.y);
for(let i=1;i<=3600;i++)flight.update(i/30);
assert.equal(meshCount(),count,'long loading flights recycle scenery without accumulating objects');
assert.notDeepEqual(flight.drone.children.filter(o=>o.isGroup).map(o=>o.rotation.y),initial,'rotors animate');
assert.equal(flight.camera.aspect,1280/720);
let disposed=0;flight.scene.traverse(o=>o.geometry?.addEventListener('dispose',()=>disposed++));flight.dispose();
assert(disposed>0);assert.equal(flight.scene.children.length,0);assert.equal(disposedOriginal,0,'flight disposal does not dispose source model');
geometry.dispose();material.dispose();
console.log('PASS visible equipped cargo snapshot, custom geometry, relative transforms, bounded flight scenery and resource cleanup');
