import {makeEquipment} from '../equipment.js';
import assert from 'node:assert/strict';
import {createCampaign,createTrainingRun,frameStats,tickBattery,spendBattery,makePart,makeWeapon} from '../salvage-campaign.js';
const data=new Map();let writes=0;
const storage={getItem:k=>data.get(k)||null,setItem:(k,v)=>{writes++;data.set(k,v);}};
const campaign=createCampaign(storage);
const frame=campaign.frame();frame.hp=63;frame.parts=[makePart('reactor','r'),makePart('drive','d'),makePart('weapon','w')];
frame.parts.forEach((p,i)=>p.slot=i);
frame.equipment={chest:makeEquipment('vest','v'),back:makeEquipment('jetPack','j')};
frame.weaponSlots=[makeWeapon('rapid','m',3),makeWeapon('bow','b',2)];campaign.state.ammo={rapid:91,bow:13};campaign.save();
const before=JSON.stringify([...data]),count=writes;
const preview=createCampaign(storage,{readOnly:true});
const run=createTrainingRun(preview.frame(),preview.state.ammo,{rapid:240,bow:30});
assert.deepEqual(run.stats,frameStats(preview.frame()));assert.deepEqual(run.weapons,['rapid','bow']);
assert.deepEqual(run.ammo,{rapid:91,bow:13});assert.equal(run.initialHP,63/100*run.stats.maxHP);
const real=campaign.launch(['rapid','bow'],{rapid:240,bow:30});
for(const key of ['stats','weaponItems','initialHP','battery','ammo'])assert.deepEqual(run[key],real[key]);
const energy=run.battery;tickBattery(run,10,4);assert(run.battery<energy);assert(spendBattery(run,6));
run.weaponItems[0].level=99;assert.notEqual(preview.frame().weaponSlots[0].level,99);
const second=createTrainingRun(preview.frame(),preview.state.ammo,{rapid:240,bow:30});assert.equal(second.battery,energy);assert.equal(second.ammo.rapid,91);
assert.equal(writes,count+1,'only the explicit real launch writes; training never saves');
const trainingOnly=new Map(JSON.parse(before));let attempted=0;
const read=createCampaign({getItem:k=>trainingOnly.get(k)||null,setItem(){attempted++;}},{readOnly:true});createTrainingRun(read.frame(),read.state.ammo,{rapid:240,bow:30});assert.equal(attempted,0);
console.log('PASS current frame, gear, modules, weapon levels, real launch parity, finite battery, isolated retry and storage');
